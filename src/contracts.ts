import { z } from 'zod';

export const requestSchema = z.object({
  claim: z.string().trim().min(5).max(2000),
  context: z.string().trim().max(4000).optional(),
  source_url: z.url().max(2048).optional(),
  as_of: z.iso.datetime().optional(),
  sources: z.array(z.enum(['web', 'x', 'reddit'])).min(1).max(3)
    .default(['web', 'x', 'reddit']).transform((s) => [...new Set(s)]),
}).strict();
export type VerifyRequest = z.infer<typeof requestSchema>;

export interface Evidence {
  id: string;
  source: 'web' | 'x' | 'reddit';
  url: string;
  author?: string;
  published_at?: string;
  retrieved_at: string;
  text: string;
  scope: 'search_snippet' | 'source_document' | 'post' | 'thread_comment';
  title?: string;
  retrieval_provider?: string;
  content_truncated?: boolean;
  content_sha256?: string;
  // Only populated from retrieved content, never generated by the model.
  excerpt?: string;
}

export const assessmentSchema = z.object({
  verdict: z.enum(['supported', 'refuted', 'mixed', 'insufficient_evidence', 'not_fact_checkable']),
  summary: z.string().min(1).max(3000),
  atomic_claims: z.array(z.object({
    claim: z.string().min(1).max(2000),
    verdict: z.enum(['supported', 'refuted', 'mixed', 'insufficient_evidence', 'not_fact_checkable']),
    explanation: z.string().min(1).max(3000),
    evidence_ids: z.array(z.string()).max(20),
  })).min(1).max(10),
  citations: z.array(z.object({
    evidence_id: z.string(),
    quote: z.string().min(1).max(2000),
    relation: z.enum(['supports', 'contradicts', 'context']),
  })).max(20),
  limitations: z.array(z.string().max(1000)).max(15),
  next_steps: z.array(z.string().max(1000)).max(10),
}).strict();
export type Assessment = z.infer<typeof assessmentSchema>;

export class ServiceError extends Error {
  constructor(public status: number, public code: string, message: string) {
    super(message);
  }
}
